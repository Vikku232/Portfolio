// Master Tech Icon resolver
export function renderTechIcon(name, size = 15, className = '') {
  const n = (name || '').trim().toLowerCase();
  
  if (n.includes('python')) return <PythonIcon size={size} className={className} />;
  if (n.includes('machine learning') || n === 'ml') return <MachineLearningIcon size={size} className={className} />;
  if (n.includes('generative ai') || n.includes('gen ai') || n === 'genai') return <GenerativeAiIcon size={size} className={className} />;
  if (n.includes('rag')) return <RagIcon size={size} className={className} />;
  if (n.includes('spring boot') || n.includes('springboot')) return <SpringBootIcon size={size} className={className} />;
  if (n === 'java' || n.startsWith('java ')) return <JavaIcon size={size} className={className} />;
  if (n.includes('react')) return <ReactIcon size={size} className={className} />;
  if (n.includes('playwright')) return <PlaywrightIcon size={size} className={className} />;
  if (n.includes('pytest')) return <PytestIcon size={size} className={className} />;
  if (n.includes('html')) return <Html5Icon size={size} className={className} />;
  if (n.includes('css')) return <Css3Icon size={size} className={className} />;
  if (n.includes('javascript') || n.includes('js')) return <JavaScriptIcon size={size} className={className} />;
  if (n.includes('typescript') || n.includes('ts')) return <TypeScriptIcon size={size} className={className} />;
  if (n.includes('tailwind')) return <TailwindIcon size={size} className={className} />;
  if (n.includes('git') && !n.includes('sqlite')) return <GitIcon size={size} className={className} />;
  if (n.includes('github')) return <GithubIcon size={size} className={className} />;
  if (n.includes('responsive')) return <ResponsiveLayoutIcon size={size} className={className} />;
  if (n.includes('ui/ux') || n.includes('design') || n.includes('creative')) return <UiUxIcon size={size} className={className} />;
  if (n.includes('three') || n.includes('webgl')) return <ThreeJsIcon size={size} className={className} />;
  if (n.includes('gsap') || n.includes('scrolltrigger') || n.includes('motion')) return <GsapIcon size={size} className={className} />;
  if (n.includes('docker')) return <DockerIcon size={size} className={className} />;
  if (n.includes('postgres')) return <PostgresIcon size={size} className={className} />;
  if (n.includes('sqlite')) return <SqliteIcon size={size} className={className} />;
  if (n.includes('mysql')) return <MysqlIcon size={size} className={className} />;
  if (n.includes('sql')) return <SqlIcon size={size} className={className} />;
  if (n.includes('rest') || n.includes('api')) return <RestApiIcon size={size} className={className} />;
  if (n.includes('hibernate')) return <HibernateIcon size={size} className={className} />;
  if (n.includes('postman')) return <PostmanIcon size={size} className={className} />;
  if (n.includes('vscode')) return <VSCodeIcon size={size} className={className} />;
  if (n.includes('intellij')) return <IntelliJIcon size={size} className={className} />;
  if (n.includes('oop')) return <OopIcon size={size} className={className} />;
  if (n.includes('dsa')) return <DsaIcon size={size} className={className} />;
  if (n.includes('mvc')) return <MvcIcon size={size} className={className} />;
  if (n.includes('dto')) return <DtoIcon size={size} className={className} />;
  
  return null;
}
